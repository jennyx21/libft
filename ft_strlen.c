#include "libft.h"

size_t	ft_strlen(const char *s)
{
	int	i;

	i = 1;
	while (*s != '\0')
	{
		s++;
		i++;
	}
	return (i);
}

int	main(void)
{
	printf(("%zu\n"), ft_strlen("hello world"));
}
